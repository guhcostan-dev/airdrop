/**
 * Wire protocol shared by the server, the CLI and (mirrored in Java/ObjC) the
 * native clients. Bump PROTOCOL_VERSION on any breaking change.
 */
export const PROTOCOL_VERSION = 1;

export type Platform = "ios" | "android";
export const PLATFORMS: readonly Platform[] = ["ios", "android"];

/** One file belonging to an update. Files are content-addressed by SHA-256. */
export interface UpdateFile {
  /** Path relative to the update root, always with forward slashes. */
  path: string;
  /** Lowercase hex SHA-256 of the *uncompressed* file contents. */
  hash: string;
  /** Uncompressed size in bytes. */
  size: number;
}

/** A file as served to devices (adds the download URL). */
export interface ServedFile extends UpdateFile {
  url: string;
}

/** What the CLI uploads when publishing an update. */
export interface PublishUpdateRequest {
  /** UUID generated by the CLI so it can be covered by the signature. */
  id: string;
  channel: string;
  platform: Platform;
  runtimeVersion: string;
  message?: string;
  mandatory?: boolean;
  /** 1..100 — percentage of devices that receive the update. */
  rolloutPercentage?: number;
  launchAsset: UpdateFile;
  assets: UpdateFile[];
  /** Base64 DER ECDSA-P256-SHA256 signature over `signingMessage()`. */
  signature?: string;
}

export interface UpdateManifest {
  id: string;
  createdAt: string;
  channel: string;
  platform: Platform;
  runtimeVersion: string;
  message: string | null;
  mandatory: boolean;
  launchAsset: ServedFile;
  assets: ServedFile[];
  signature: string | null;
}

export interface CheckRequest {
  appId: string;
  channel?: string;
  platform: Platform;
  runtimeVersion: string;
  /** Random per-install identifier used for staged rollouts. */
  deviceId: string;
  /** Update currently running, or null/undefined when running the embedded bundle. */
  currentUpdateId?: string | null;
  /** Native SDK version, for diagnostics. */
  sdkVersion?: string;
}

export type CheckResponse =
  | { status: "noUpdate" }
  | { status: "update"; update: UpdateManifest }
  | { status: "rollbackToEmbedded" };

export type ClientEventType = "download" | "install" | "rollback" | "error";

export interface ClientEvent {
  type: ClientEventType;
  updateId: string;
  message?: string;
}

export interface EventsRequest {
  appId: string;
  deviceId: string;
  events: ClientEvent[];
}
